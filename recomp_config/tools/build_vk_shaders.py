"""Compiles the GPU back end's HLSL to SPIR-V for the Vulkan back end.

The shaders are the D3D11 back end's own (s_hlsl in src/gpu_d3d11.c), so the
two renderers run the same shader code. This pulls that C string out,
compiles each entry point with DXC's SPIR-V back end and writes
src/gpu_vk_spirv.h, which src/gpu_vk.c includes. Run it again whenever
s_hlsl changes; the header records the source's hash, and gpu_vk.c's build
fails to match it if they drift (see GZ_VK_HLSL_HASH).

Register mapping (one descriptor set, set 0):
    b0..b3 -> bindings 0..3   (uniform buffers)
    t0..t7 -> bindings 16..23 (sampled images: tx0..tx3, cx0..cx3)
    s0..s3 -> bindings 32..35 (samplers)

    python recomp_config/tools/build_vk_shaders.py --dxc <path to dxc.exe or dxc>
"""
import argparse
import ast
import hashlib
import os
import re
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, "src", "gpu_d3d11.c")
OUT = os.path.join(ROOT, "src", "gpu_vk_spirv.h")

# (C name, entry point, profile)
ENTRIES = [
    ("vs_main", "vs_main", "vs_6_0"),
    ("ps_main", "ps_main", "ps_6_0"),
    ("vs_blit", "vs_blit", "vs_6_0"),
    ("ps_blit", "ps_blit", "ps_6_0"),
    ("ps_one", "ps_one", "ps_6_0"),
    ("vs_prog", "vs_prog", "vs_6_0"),
]


def hlsl_source():
    text = open(SRC, encoding="utf-8").read()
    m = re.search(r"static const char s_hlsl\[\] =\s*\n(.*?);\s*\n", text, re.S)
    if not m:
        sys.exit("s_hlsl not found in " + SRC)
    out = []
    for lit in re.findall(r'"((?:[^"\\]|\\.)*)"', m.group(1)):
        out.append(ast.literal_eval('"' + lit + '"'))
    return "".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dxc", required=True)
    args = ap.parse_args()
    src = hlsl_source()
    digest = hashlib.sha1(src.encode("utf-8")).hexdigest()[:16]
    tmp = tempfile.mkdtemp(prefix="gz_vk_")
    hlsl = os.path.join(tmp, "gz_gpu.hlsl")
    with open(hlsl, "w", encoding="utf-8", newline="\n") as f:
        f.write(src)
    lines = [
        "/* Generated by recomp_config/tools/build_vk_shaders.py from s_hlsl in",
        " * src/gpu_d3d11.c. Do not edit; run the script again instead. */",
        "#ifndef GPU_VK_SPIRV_H",
        "#define GPU_VK_SPIRV_H",
        "#include <stdint.h>",
        '#define GZ_VK_HLSL_HASH "%s"' % digest,
    ]
    for name, entry, profile in ENTRIES:
        spv = os.path.join(tmp, name + ".spv")
        # -HV 2018: the language d3dcompiler (ps_5_0) accepts, e.g. per-lane
        # vector ?: in vs_prog, which HLSL 2021 turned into an error.
        cmd = [args.dxc, "-spirv", "-HV", "2018", "-T", profile, "-E", entry, "-O3",
               "-fspv-target-env=vulkan1.3", "-fvk-use-dx-layout",
               "-fvk-b-shift", "0", "0", "-fvk-t-shift", "16", "0", "-fvk-s-shift", "32", "0",
               "-Fo", spv, hlsl]
        if profile.startswith("vs"):
            cmd.insert(1, "-fvk-invert-y")
        r = subprocess.run(cmd, capture_output=True, text=True)
        if r.returncode != 0:
            sys.stderr.write(r.stdout + r.stderr)
            sys.exit("dxc failed for " + entry)
        data = open(spv, "rb").read()
        words = [int.from_bytes(data[i:i + 4], "little") for i in range(0, len(data), 4)]
        lines.append("static const uint32_t gz_spv_%s[%d] = {" % (name, len(words)))
        for i in range(0, len(words), 8):
            lines.append("    " + ", ".join("0x%08Xu" % w for w in words[i:i + 8]) + ",")
        lines.append("};")
        print("%-8s %6d bytes" % (name, len(data)))
    lines.append("#endif")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("Wrote " + OUT + " (s_hlsl " + digest + ")")


if __name__ == "__main__":
    main()
